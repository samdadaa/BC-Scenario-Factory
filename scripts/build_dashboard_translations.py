#!/usr/bin/env python3
"""Bundle dashboard fallback translations from the maintained XLIFF master; --check detects drift."""

import argparse
import json
from pathlib import Path
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/Monitoring/Dashboard/translations.js"
NS = {"x": "urn:oasis:names:tc:xliff:document:1.2"}
OBJECTS = ("Codeunit BCSF Dashboard Stock - ", "Codeunit BCSF Dashboard Data - ", "Codeunit BCSF Monitoring Mgt - ",
           "Codeunit BCSF Validation Manager - ", "Enum BCSF Run Status - ",
           "Enum BCSF Validation Severity - ",
           "Enum BCSF Entity Type - ", "Enum BCSF Module Type - ", "Enum BCSF Process Mode - ")


def render():
    tree = ET.parse(ROOT / "Translations/BC Scenario Factory.de-DE.xlf")
    translations = {}
    for unit in tree.findall(".//x:trans-unit", NS):
        note = unit.find("x:note[@from='Xliff Generator']", NS)
        if note is None or not (note.text or "").startswith(OBJECTS):
            continue
        source = unit.find("x:source", NS)
        target = unit.find("x:target", NS)
        if target is None or target.get("state") != "translated" or not target.text:
            raise ValueError(f"Missing reviewed dashboard translation: {unit.attrib['id']}")
        if source.text in translations and translations[source.text] != target.text:
            raise ValueError(f"Ambiguous dashboard translation: {source.text}")
        translations[source.text] = target.text
    if not translations:
        raise ValueError("No dashboard translations found")
    # Use the reviewed language map for new labels before their compiler-generated XLIFF IDs exist.
    extra = json.loads((ROOT / "Translations/sf041.de.json").read_text(encoding="utf-8"))
    extra.update(json.loads((ROOT / "Translations/sf044.de.json").read_text(encoding="utf-8")))
    for source, target in extra.items():
        translations.setdefault(source, target)
    catalog = json.dumps({"de": translations}, ensure_ascii=True, sort_keys=True, indent=2)
    return "// Generated by scripts/build_dashboard_translations.py from de-DE XLIFF; do not edit.\n" + \
        "window.BCSFDashboardTranslations = " + catalog + ";\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            raise SystemExit("Stale dashboard translations; run python3 scripts/build_dashboard_translations.py")
    else:
        OUTPUT.write_text(expected)
    print("PASS: dashboard fallback matches reviewed XLIFF translations.")


if __name__ == "__main__":
    main()
